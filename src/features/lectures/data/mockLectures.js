/**
 * Helper to fetch a lecture by ID with fallback
 */
export const getLectureById = (id) => {
  const found = MOCK_LECTURES.find((lec) => lec.id === String(id));
  if (found) return found;

  const num = parseInt(id, 10) || 1;
  return {
    id: String(id),
    number: `Lecture ${num.toString().padStart(2, '0')}`,
    title: `Lecture ${num.toString().padStart(2, '0')}`,
    description: 'DSP lecture presentation slides and course material.',
    videoType: 'external',
    hasVideo: true,
    hasPdf: true,
    videoDuration: '45:00',
    videoUrl: null,
    externalDriveUrl: 'https://drive.google.com/drive/folders/1nBxzW5s3j9pr2YbGMbP1MZvEuqTwOzUv',
    pdfDriveId: null,
    pdfFileName: `Lecture ${num}.pdf`,
  };
};
